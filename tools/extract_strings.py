#!/usr/bin/env python3
"""Extract the shell's translatable strings into a .pot template.

The QML sources use Tr.tr / Tr.trCtx / Tr.trN / Tr.trCtxN, which upstream
xgettext scans for when building its own catalogs. This does the same job for
the JSON dictionaries, so translators get one file to work from:

    python3 tools/extract_strings.py            # -> i18n/messages.pot
    python3 tools/extract_strings.py --json     # -> i18n/messages.json
"""
import json
import os
import re
import sys

ROOT = os.path.expanduser("~/.config/quickshell/caelestia")
I18N = os.path.join(ROOT, "i18n")

CALL = re.compile(r"Tr\.(tr|trCtx|trN|trCtxN)\(\s*")
# QML strings may be single- or double-quoted; both appear in the sources.
STR = re.compile(r'"((?:[^"\\]|\\.)*)"|\'((?:[^\'\\]|\\.)*)\'')

# Which positional args must be string literals for a key to be extractable.
# trN/trCtxN take a trailing count that is legitimately a variable.
LITERAL_ARGS = {
    "tr": (0,),
    "trCtx": (0, 1),
    "trN": (0, 1),
    "trCtxN": (0, 1, 2),
}

MARK, ARG, PLURAL, CONTEXT = "", "", "", ""


def unescape(s):
    return (s.replace('\\"', '"').replace("\\n", "\n")
             .replace("\\t", "\t").replace("\\\\", "\\"))


def split_args(src, i):
    """Parse a call's argument list at i.

    Each element is the unescaped value of a plain string literal, or None for
    any other expression. Commas separate arguments and are not themselves
    arguments.
    """
    args, n = [], len(src)
    while i < n:
        while i < n and (src[i].isspace() or src[i] == ","):
            i += 1
        if i >= n:
            return None
        if src[i] == ")":
            return args
        if src[i] == '"':
            m = STR.match(src, i)
            if not m:
                return None
            args.append(unescape(m.group(1) if m.group(1) is not None else m.group(2)))
            i = m.end()
            continue
        depth = 0
        while i < n:
            c = src[i]
            if c in "([{":
                depth += 1
            elif c in ")]}":
                if depth == 0:
                    break
                depth -= 1
            elif c == "," and depth == 0:
                break
            elif c == '"':
                m = STR.match(src, i)
                if not m:
                    return None
                i = m.end() - 1
            i += 1
        args.append(None)
    return None


def key_for(kind, args):
    if kind == "tr":
        return args[0]
    if kind == "trCtx":
        return args[1] + CONTEXT + args[0]
    if kind == "trN":
        return args[0] + PLURAL + args[1]
    if kind == "trCtxN":
        return args[2] + CONTEXT + args[0] + PLURAL + args[1]
    return None


def po_escape(s):
    return (s.replace("\\", "\\\\").replace('"', '\\"')
             .replace("\n", "\\n").replace("\t", "\\t"))


def dict_key(key):
    """Split a gettext-style key back into (context, singular, plural)."""
    ctx = ""
    if CONTEXT in key:
        ctx, key = key.split(CONTEXT, 1)
    if PLURAL in key:
        s, p = key.split(PLURAL, 1)
        return ctx, s, p
    return ctx, key, None


def main():
    plain, plural = {}, {}

    for dirpath, _, filenames in os.walk(ROOT):
        if "Caelestia" in dirpath.split(os.sep):  # skip the shadowed module
            continue
        for fn in filenames:
            if not fn.endswith(".qml"):
                continue
            path = os.path.join(dirpath, fn)
            src = open(path, encoding="utf-8").read()
            rel = os.path.relpath(path, ROOT)
            for m in CALL.finditer(src):
                args = split_args(src, m.end())
                if args is None:
                    continue
                want = LITERAL_ARGS[m.group(1)]
                if any(args[i] is None for i in want if i < len(args)):
                    continue
                key = key_for(m.group(1), args)
                if not key:
                    continue
                line = src.count("\n", 0, m.start()) + 1
                loc = f"{rel}:{line}"
                if PLURAL in key:
                    ctx, s, p = dict_key(key)
                    plural.setdefault((ctx, s, p), set()).add(loc)
                else:
                    plain.setdefault(key, set()).add(loc)

    os.makedirs(I18N, exist_ok=True)

    if "--json" in sys.argv:
        out = {k: "" for k in sorted(plain)}
        for ctx, s, p in plural:
            out[(ctx + CONTEXT if ctx else "") + s + PLURAL + p] = []
        with open(os.path.join(I18N, "messages.json"), "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=1)
        print("messages.json:", len(out), "entries")
        return

    lines = [
        '# Caelestia shell UI strings.',
        '# Generated by tools/extract_strings.py -- do not edit by hand.',
        '#',
        '# Placeholders: %1..%n are substituted at runtime and MUST be kept',
        '# in translations. %n is a plural count.',
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: caelestia-shell\\n"',
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        '',
    ]

    def emit(ctx, s, p, locs):
        lines.append("#: " + " ".join(sorted(locs)))
        if ctx:
            lines.append(f'msgctxt "{po_escape(ctx)}"')
        lines.append(f'msgid "{po_escape(s)}"')
        if p is None:
            lines.append('msgstr ""')
        else:
            lines.append(f'msgid_plural "{po_escape(p)}"')
            lines.append('msgstr[0] ""')
            lines.append('msgstr[1] ""')
        lines.append("")

    for key in sorted(plain):
        ctx, s, p = dict_key(key)
        emit(ctx, s, p, plain[key])
    for (ctx, s, p) in sorted(plural):
        emit(ctx, s, p, plural[(ctx, s, p)])

    with open(os.path.join(I18N, "messages.pot"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("messages.pot:", len(plain) + len(plural), "entries")


if __name__ == "__main__":
    main()
