#!/usr/bin/env python3
"""Generate the shadowing Caelestia.I18n module.

QML cannot create FileViews from JS, so this emits one static FileView per
shipped dictionary and splices them into Tr.qml. Run after adding a language:

    python3 tools/gen_i18n_module.py
"""
import os
import shutil

ROOT = os.path.expanduser("~/.config/quickshell/caelestia")
I18N = os.path.join(ROOT, "i18n")
OUT = os.path.join(ROOT, "Caelestia", "I18n")
UNITS_SRC = "/usr/lib/qt6/qml/Caelestia/I18n/Units.qml"

TR_TEMPLATE = r'''pragma Singleton

import QtQuick
import Quickshell
import Caelestia.Config

// Drop-in replacement for the Caelestia.I18n Tr singleton.
//
// The upstream translator reads .mo catalogs compiled into the plugin, and
// upstream ships none, so it always falls back to English. This loads plain
// JSON dictionaries from i18n/ at runtime instead, so languages can be added
// without rebuilding the plugin.
//
// It shadows the plugin by living at <config>/Caelestia/I18n and being placed
// ahead of /usr/lib/qt6/qml in QML2_IMPORT_PATH (see shell.qml), so all 1165
// existing `Tr.tr(...)` call sites keep working untouched.
//
// Generated by tools/gen_i18n_module.py -- do not edit by hand.

QtObject {
    id: root

    // Directory holding locales.json and the per-language dictionaries.
    readonly property string dir: "__I18N_DIR__"

    // Bumped on every catalog change so bindings that called tr() re-evaluate.
    // Mirrors the upstream `__trsChanged` flag.
    property string __trsChanged: ""

    // The active language. Empty means "follow the system locale".
    // Persisted through the shell's own config so it survives restarts.
    property string language: GlobalConfig.general.language ?? ""

    property var _locales: []
    property var _catalog: ({})
    property var _active: ""

    // code -> FileView, so reload() can read .data() off each one.
    property var _dictViews: ({
__DICT_MAPPING__
    })

    // Locales that have a dictionary available, for the picker.
    readonly property var supportedLanguages: {
        const out = [];
        for (const loc of root._locales) {
            if (root._dictViews[loc.code] !== undefined)
                out.push(loc.code);
        }
        return out;
    }

    onLanguageChanged: root.reload()

    Component.onCompleted: {
        root._locales = localesView.data() ?? [];
        root.reload();
    }

    // Locale inventory, read synchronously at startup.
    FileView {
        id: localesView
        path: root.dir + "/locales.json"
        blockLoading: true
        printErrors: false
    }

__DICT_VIEWS__

    // Resolves the configured language to a concrete code, or "" for auto.
    function _resolve() {
        if (root.language !== "")
            return root.language;
        for (const ui of Qt.locale().uiLanguages) {
            const norm = ui.replace("-", "_");
            if (root._dictViews[norm] !== undefined)
                return norm;
            const base = norm.split("_")[0];
            if (root._dictViews[base] !== undefined)
                return base;
        }
        return "";
    }

    // Reads the dictionary for the active language, merged over its base
    // language so a variant only needs the strings that actually differ.
    function reload() {
        root._catalog = ({});
        const lang = root._resolve();
        root._active = lang;
        if (lang === "") {
            root.__trsChanged = String(Date.now());
            return;
        }

        const chain = lang.includes("_") ? [lang, lang.split("_")[0]] : [lang];
        // Base first, so the exact locale overrides it.
        for (const code of chain) {
            const view = root._dictViews[code];
            if (view === undefined)
                continue;
            const data = view.data();
            if (data)
                Object.assign(root._catalog, data);
        }

        root.__trsChanged = String(Date.now());
    }

    // CLDR plural category for a language and count.
    function _plural(n) {
        const lang = (root._active || "en").split("_")[0];
        const i = Math.abs(n);
        const m10 = i % 10;
        const m100 = i % 100;

        switch (lang) {
        // No plural distinction
        case "ja": case "ko": case "zh": case "th": case "vi":
        case "id": case "ms": case "my": case "km": case "lo":
            return 0;
        // 0 and 1 are singular here
        case "fr": case "pt": case "tr": case "hy": case "kab":
            return (i === 0 || i === 1) ? 0 : 1;
        case "ru": case "uk": case "be":
            if (m10 === 1 && m100 !== 11) return 0;
            if (m10 >= 2 && m10 <= 4 && !(m100 >= 12 && m100 <= 14)) return 1;
            return 2;
        case "pl":
            if (i === 1) return 0;
            if (m10 >= 2 && m10 <= 4 && !(m100 >= 12 && m100 <= 14)) return 1;
            return 2;
        case "cs": case "sk":
            if (i === 1) return 0;
            if (i >= 2 && i <= 4) return 1;
            return 2;
        case "sl":
            if (m100 === 1) return 0;
            if (m100 === 2) return 1;
            if (m100 === 3 || m100 === 4) return 2;
            return 3;
        case "ar":
            if (i === 0) return 0;
            if (i === 1) return 1;
            if (i === 2) return 2;
            if (m100 >= 3 && m100 <= 10) return 3;
            if (m100 >= 11) return 4;
            return 5;
        case "he":
            if (i === 1) return 0;
            if (i === 2) return 1;
            return 2;
        case "lt":
            if (m10 === 1 && !(m100 >= 11 && m100 <= 19)) return 0;
            if (m10 >= 2 && m10 <= 9 && !(m100 >= 11 && m100 <= 19)) return 1;
            return 2;
        case "lv": case "prg":
            if (m10 === 0 || (m100 >= 11 && m100 <= 19)) return 0;
            if (m10 === 1 && m100 !== 11) return 1;
            return 2;
        case "ro":
            if (i === 1) return 0;
            if (i === 0 || (m100 >= 1 && m100 <= 19)) return 1;
            return 2;
        default:
            return i === 1 ? 0 : 1;
        }
    }

    // Replaces %n / %Ln with the count, formatted for the active locale.
    function _subst(text, n) {
        return text.replace(/%L?n/g, () => _formatNumber(n));
    }

    function _formatNumber(n) {
        return Number(n).toLocaleString(Qt.locale(root._active || "en_US"), "f", 0);
    }

    // Reads __trsChanged so bindings that call tr() re-evaluate on switch.
    function _touch() {
        return root.__trsChanged;
    }

    // Picks the translation for a plural entry, which may be a string or an
    // array with one form per plural category.
    function _pickForm(hit, n, fallback) {
        if (hit === undefined)
            return fallback;
        const forms = Array.isArray(hit) ? hit : [hit];
        const form = forms[Math.min(root._plural(n), forms.length - 1)];
        return typeof form === "string" ? form : fallback;
    }

    // ------------------------------------------------------------------
    // Public API, matching the upstream Tr singleton
    // ------------------------------------------------------------------

    function tr(text: string): string {
        root._touch();
        if (root._isMarked(text))
            return root._translateMarked(text);
        const hit = root._catalog[text];
        return hit === undefined ? text : hit;
    }

    function trCtx(text: string, context: string): string {
        root._touch();
        const hit = root._catalog[context + CONTEXT + text];
        return hit === undefined ? text : hit;
    }

    function trN(text: string, plural: string, n: int): string {
        root._touch();
        const hit = root._catalog[text + PLURAL + plural];
        return root._subst(root._pickForm(hit, n, root._plural(n) === 0 ? text : plural), n);
    }

    function trCtxN(text: string, plural: string, n: int, context: string): string {
        root._touch();
        const hit = root._catalog[context + CONTEXT + text + PLURAL + plural];
        return root._subst(root._pickForm(hit, n, root._plural(n) === 0 ? text : plural), n);
    }

    function trMarked(text: string): string {
        root._touch();
        return root._isMarked(text) ? root._translateMarked(text) : text;
    }

    // ------------------------------------------------------------------
    // Marked strings. The wire format matches upstream exactly:
    //   ^A {<arg> ^B}? [^D context ^D]? text [^C plural ^C n]?
    // so strings marked by the plugin's Tr.mark stay interchangeable.
    // ------------------------------------------------------------------

    function mark(text: string, args: list<string> = []): string {
        return root._doMark(text, "", -1, "", args);
    }

    function markCtx(text: string, context: string, args: list<string> = []): string {
        return root._doMark(text, "", -1, context, args);
    }

    function markN(text: string, plural: string, n: int, args: list<string> = []): string {
        return root._doMark(text, plural, n, "", args);
    }

    function markCtxN(text: string, plural: string, n: int, context: string, args: list<string> = []): string {
        return root._doMark(text, plural, n, context, args);
    }

    function _doMark(text, plural, n, context, args) {
        let out = MARK;
        for (const a of args)
            out += a + ARG;
        if (context !== "")
            out += context + CONTEXT;
        out += text;
        if (n >= 0)
            out += PLURAL + plural + PLURAL + n;
        return out;
    }

    function _isMarked(text) {
        return typeof text === "string" && text.length > 0 && text.charCodeAt(0) === 1;
    }

    function _parseMarked(text) {
        let body = text.slice(1);
        let args = [];
        let context = "";

        const argEnd = body.lastIndexOf(ARG);
        if (argEnd >= 0) {
            args = body.slice(0, argEnd).split(ARG);
            body = body.slice(argEnd + 1);
        }
        const ctxEnd = body.indexOf(CONTEXT);
        if (ctxEnd >= 0) {
            context = body.slice(0, ctxEnd);
            body = body.slice(ctxEnd + 1);
        }
        const parts = body.split(PLURAL);
        return {
            text: parts[0],
            plural: parts.length === 3 ? parts[1] : "",
            n: parts.length === 3 ? parseInt(parts[2]) : -1,
            context: context,
            args: args
        };
    }

    // Translates a marked string, recursing into any marked arguments.
    function _translateMarked(text) {
        const m = root._parseMarked(text);
        const key = (m.context !== "" ? m.context + CONTEXT : "") + m.text
            + (m.n < 0 ? "" : PLURAL + m.plural);
        const hit = root._catalog[key];

        let result;
        if (m.n < 0) {
            result = hit === undefined ? m.text : hit;
        } else {
            result = root._subst(
                root._pickForm(hit, m.n, m.n === 1 ? m.text : m.plural), m.n);
        }

        for (const a of m.args)
            result = result.arg(root._isMarked(a) ? root._translateMarked(a) : a);
        return result;
    }

    // Control characters of the marked-string wire format, matching
    // util/i18n.hpp in the upstream plugin.
    readonly property string MARK: "\u0001"
    readonly property string ARG: "\u0002"
    readonly property string PLURAL: "\u0003"
    readonly property string CONTEXT: "\u0004"
}
'''


def shipped_languages():
    """Language codes with a dictionary on disk, base languages only.

    Territory variants inherit from their base through the fallback chain, so
    only `id.json` is needed, not `id_ID.json`.
    """
    langs = []
    for fn in sorted(os.listdir(I18N)):
        if not fn.endswith(".json") or fn == "locales.json":
            continue
        code = fn[:-5]
        if "_" not in code:
            langs.append(code)
    return langs


def main():
    langs = shipped_languages()
    os.makedirs(OUT, exist_ok=True)

    views = "\n\n".join(
        f"""    FileView {{
        id: dict_{code}
        path: root.dir + "/{code}.json"
        blockLoading: true
        printErrors: false
    }}"""
        for code in langs
    )
    mapping = ",\n".join(f'        "{code}": dict_{code}' for code in langs)

    body = (TR_TEMPLATE
            .replace("__I18N_DIR__", I18N)
            .replace("__DICT_VIEWS__", views)
            .replace("__DICT_MAPPING__", mapping))

    with open(os.path.join(OUT, "Tr.qml"), "w", encoding="utf-8") as f:
        f.write(body)

    with open(os.path.join(OUT, "qmldir"), "w", encoding="utf-8") as f:
        f.write(
            "module Caelestia.I18n\n"
            "# Shadows the installed caelestia-i18n plugin. Reached by putting\n"
            "# this directory ahead of /usr/lib/qt6/qml in QML2_IMPORT_PATH.\n"
            "singleton Tr 254.0 Tr.qml\n"
            "singleton Units 254.0 Units.qml\n"
        )

    # Units is pure QML and only calls Tr, so the installed copy works as-is
    # once Tr resolves to ours.
    if os.path.exists(UNITS_SRC):
        shutil.copy(UNITS_SRC, os.path.join(OUT, "Units.qml"))

    print("languages:", ", ".join(langs) or "(none)")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
